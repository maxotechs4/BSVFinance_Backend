package com.microfinance.entity.enums;

/**
 * The day of the week a member is assigned to for collection visits.
 * Selected on the Create Member form and used by the Admin page's
 * weekday filter to group members for the field-collection round.
 */
public enum Weekday {
    MONDAY,
    TUESDAY,
    WEDNESDAY,
    THURSDAY,
    FRIDAY,
    SATURDAY,
    SUNDAY
}
